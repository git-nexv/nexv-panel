/**
 * Whose address is this?
 *
 * Sniffing names the destination of most connections, but not all: a client
 * that dials an address directly - a torrent peer, a DNS resolver, an app that
 * pins its own IPs, anything over a protocol the inbound does not sniff -
 * leaves a bare number in the log. A page of bare numbers tells an admin
 * nothing, and "I do not know what these are" is the most common thing anybody
 * asks about this screen.
 *
 * So the big, stable allocations are written down here and matched by prefix.
 * This is deliberately a table and not a lookup:
 *
 *   - it works on a server with no outbound access, which is the normal case
 *     for a panel sitting behind a filter;
 *   - it costs nothing per connection, where a reverse lookup costs a round
 *     trip per address and leaks who is browsing what to whoever answers it;
 *   - it cannot be wrong in an interesting way: a prefix either covers an
 *     address or it does not.
 *
 * What it cannot do is name every address. Residential addresses - which is
 * what most torrent peers are - belong to thousands of local networks and are
 * not in any table worth shipping. Those stay unnamed, which is the honest
 * answer. Ranges also move over years; these are the ones that have been
 * stable for a long time, and a wrong name here is cosmetic.
 */

