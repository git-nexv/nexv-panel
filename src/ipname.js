/* '1.2.3.4' -> 16909060, or -1 when it is not a dotted quad */
function toInt(ip) {
  const parts = String(ip).split('.');
  if (parts.length !== 4) return -1;
  let n = 0;
  for (const part of parts) {
    if (!/^\d{1,3}$/.test(part)) return -1;
    const byte = Number(part);
    if (byte > 255) return -1;
    n = n * 256 + byte;
  }
  return n;
}

/* the table, flattened once into {start, end, name, kind} and sorted, so a
   lookup is a scan of numbers rather than a parse of strings */
const RANGES = [];
for (const [name, kind, prefixes] of V4) {
  for (const prefix of prefixes) {
    const [base, bitsRaw] = prefix.split('/');
    const start = toInt(base);
    const bits = Number(bitsRaw);
    if (start < 0 || !(bits >= 0 && bits <= 32)) continue;
    const size = bits === 0 ? 2 ** 32 : 2 ** (32 - bits);
    RANGES.push({ start, end: start + size - 1, name, kind });
  }
}
/* narrow first, so a single resolver address inside a provider's /16 wins */
RANGES.sort((a, b) => (a.end - a.start) - (b.end - b.start));

/**
 * Who an address belongs to, as far as the table knows.
 *
 * Returns { name, kind } or null. A null is not a failure: most residential
 * addresses - torrent peers, in particular - belong to no network worth
 * listing, and saying nothing is better than guessing.
 */
function lookup(address) {
  const ip = String(address || '').trim().replace(/^\[|\]$/g, '').toLowerCase();
  if (!ip) return null;

  if (ip.includes(':')) {
    for (const [name, kind, prefixes] of V6) {
      for (const prefix of prefixes) {
        if (ip === prefix || ip.startsWith(prefix)) return { name, kind };
      }
    }
    return null;
  }

  const n = toInt(ip);
  if (n < 0) return null;
  for (const range of RANGES) {
    if (n >= range.start && n <= range.end) return { name: range.name, kind: range.kind };
  }
  return null;
}

/** Just the name, or '' - the shape the site table wants. */
function nameOf(address) {
  const hit = lookup(address);
  return hit ? hit.name : '';
}

